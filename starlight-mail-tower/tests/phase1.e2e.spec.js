test('두 LAN 클라이언트가 준비 후 같은 30Hz 세션에서 이동한다', async ({ browser }) => {
  const contextA = await browser.newContext({ viewport: { width: 1280, height: 720 } });
  const contextB = await browser.newContext({ viewport: { width: 1280, height: 720 } });
  const pageA = await contextA.newPage();
  const pageB = await contextB.newPage();
  await Promise.all([pageA.goto('/?name=루멘'), pageB.goto('/?name=볼트')]);
  await expect(pageA.locator('body')).toHaveAttribute('data-player-id', /p[12]/);
  await expect(pageB.locator('body')).toHaveAttribute('data-player-id', /p[12]/);
  const roleA = await pageA.locator('body').getAttribute('data-player-id');
  const roleB = await pageB.locator('body').getAttribute('data-player-id');
  expect(roleA).not.toBe(roleB);
  await expect(pageA.locator('#p1-name')).not.toHaveText('…');
  await expect(pageA.locator('#p2-name')).not.toHaveText('…');
  const readyRoleBox = await pageA.locator('#p1-crew').boundingBox();
  const readyActionBox = await pageA.locator('#ready-button').boundingBox();
  expect(readyRoleBox.width).toBeGreaterThan(400);
  expect(readyRoleBox.height).toBeGreaterThanOrEqual(64);
  expect(readyActionBox).toMatchObject({ width: 160, height: 46 });
  await fs.mkdir('tests/screenshots', { recursive: true });
  await pageA.screenshot({ path: 'tests/screenshots/phase3-game-ready-1280x720.png' });
  await Promise.all([pageA.locator('#ready-button').click(), pageB.locator('#ready-button').click()]);
  await expect(pageA.locator('#ready-overlay')).toBeHidden();
  await expect(pageB.locator('#ready-overlay')).toBeHidden();
  const movingPage = roleA === 'p1' ? pageA : pageB;
  await expect(movingPage.locator('body')).toHaveAttribute('data-server-tick', /[1-9]\d*/);
  const initialX = Number(await movingPage.locator('body').getAttribute('data-player-x'));
  await movingPage.keyboard.down('KeyD');
  await movingPage.waitForTimeout(700);
  await movingPage.keyboard.up('KeyD');
  await expect.poll(async () => Number(await movingPage.locator('body').getAttribute('data-player-x'))).toBeGreaterThan(initialX + 80);
  await fs.mkdir('tests/screenshots', { recursive: true });
  await pageA.screenshot({ path: 'tests/screenshots/phase1-ingame.png' });
  await pageA.screenshot({ path: 'tests/screenshots/phase1-ingame-1280x720.png' });
  const canvasBox = await pageA.locator('#game-canvas').boundingBox();
  const toolbarBox = await pageA.locator('.toolbar').boundingBox();
  expect(canvasBox.width).toBe(1280);
  expect(canvasBox.height).toBe(720);
  expect(canvasBox.width / canvasBox.height).toBeCloseTo(16 / 9, 5);
  expect(toolbarBox.y + toolbarBox.height).toBeLessThanOrEqual(94);
  await contextA.close();
  await contextB.close();
});

test('1024×576에서 Canvas와 기본 HUD가 화면 안에 유지된다', async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 1024, height: 576 } });
  const partnerContext = await browser.newContext({ viewport: { width: 1024, height: 576 } });
  const page = await context.newPage();
  const partnerPage = await partnerContext.newPage();
  await Promise.all([page.goto('/?name=ABCDEFGHIJKLMNOPQRST'), partnerPage.goto('/?name=ResponsivePartner')]);
  await expect(page.locator('#p1-name')).not.toHaveCSS('text-overflow', 'ellipsis');
  await expect(page.locator('#p2-name')).not.toHaveCSS('text-overflow', 'ellipsis');
  const longName = page.getByText('ABCDEFGHIJKLMNOPQRST', { exact: true });
  await expect(longName).toBeVisible();
  expect(await longName.evaluate((element) => element.getBoundingClientRect().height)).toBeGreaterThanOrEqual(20);
  await expect(longName).toHaveText('ABCDEFGHIJKLMNOPQRST');
  const canvasBox = await page.locator('#game-canvas').boundingBox();
  const connectionBox = await page.locator('.connection-panel').boundingBox();
  const readyButtonBox = await page.locator('#ready-button').boundingBox();
  const roleCardBox = await page.locator('#p1-crew').boundingBox();
  const timerBox = await page.locator('#elapsed-time').boundingBox();
  expect(canvasBox.width).toBeLessThanOrEqual(1024);
  expect(canvasBox.height).toBeLessThanOrEqual(576);
  expect(canvasBox.width / canvasBox.height).toBeCloseTo(16 / 9, 5);
  expect(connectionBox.x + connectionBox.width).toBeLessThanOrEqual(1024);
  expect(await page.locator('.connection-panel').evaluate((element) => Number.parseFloat(getComputedStyle(element).fontSize))).toBeGreaterThanOrEqual(12);
  expect(readyButtonBox).toMatchObject({ width: 160, height: 44 });
  expect(roleCardBox.width).toBeGreaterThan(300);
  expect(roleCardBox.height).toBeGreaterThanOrEqual(64);
  await fs.mkdir('tests/screenshots', { recursive: true });
  await page.screenshot({ path: 'tests/screenshots/phase3-game-ready-1024x576.png' });
  await Promise.all([page.locator('#ready-button').click(), partnerPage.locator('#ready-button').click()]);
  await expect(page.locator('#ready-overlay')).toBeHidden();
  await page.locator('#locale-button').click();
  await expect(page).toHaveTitle('Starlight Mail Tower');
  await expect(page.locator('#game-canvas')).toHaveAttribute('aria-label', 'Starlight Mail Tower sorting deck');
  const toolbarBox = await page.locator('.toolbar').boundingBox();
  expect(toolbarBox.y).toBeGreaterThanOrEqual(timerBox.y + timerBox.height + 8);
  const hintBox = await page.locator('#action-hint').boundingBox();
  expect(576 - (hintBox.y + hintBox.height)).toBeGreaterThanOrEqual(16);
  await fs.mkdir('tests/screenshots', { recursive: true });
  await page.screenshot({ path: 'tests/screenshots/phase1-ingame-1024x576.png' });
  await context.close();
  await partnerContext.close();
});

