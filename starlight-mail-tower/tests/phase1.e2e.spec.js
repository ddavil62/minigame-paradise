test('재접속 유예 만료는 종료 오버레이와 단일 로비 경로를 제공한다', async ({ browser, request }) => {
  const contextA = await browser.newContext({ viewport: { width: 1024, height: 576 } });
  const contextB = await browser.newContext({ viewport: { width: 1024, height: 576 } });
  const pageA = await contextA.newPage(); const pageB = await contextB.newPage();
  await Promise.all([pageA.goto('/?name=ExpireA'), pageB.goto('/?name=ExpireB')]);
  await Promise.all([pageA.locator('#ready-button').click(), pageB.locator('#ready-button').click()]);
  await expect(pageA.locator('#ready-overlay')).toBeHidden();
  const toolbarBox = await pageA.locator('.toolbar').boundingBox();
  const timerBox = await pageA.locator('#elapsed-time').boundingBox();
  expect(toolbarBox && timerBox && (toolbarBox.y >= timerBox.y + timerBox.height + 8 || toolbarBox.x + toolbarBox.width + 8 <= timerBox.x || timerBox.x + timerBox.width + 8 <= toolbarBox.x)).toBe(true);
  await pageA.screenshot({ path: 'tests/screenshots/phase3-online-toolbar-1024x576.png' });
  await pageA.locator('.connection-panel').evaluate((element) => { element.dataset.state = 'connecting'; });
  await pageA.screenshot({ path: 'tests/screenshots/phase3-latency-packets-1024x576.png' });
  await pageA.locator('.connection-panel').evaluate((element) => { element.dataset.state = 'online'; });
  await pageB.close();
  await expect(pageA.locator('#reconnect-overlay')).toBeVisible();
  await pageA.emulateMedia({ reducedMotion: 'reduce' });
  await pageA.screenshot({ path: 'tests/screenshots/phase3-reconnect-reduced-motion-1024x576.png' });
  await request.post('/__test/expire-reconnect');
  await expect(pageA.locator('#session-ended-overlay')).toBeVisible();
  await expect(pageA.locator('#session-ended-overlay button')).toHaveCount(1);
  await pageA.waitForTimeout(220);
  await pageA.screenshot({ path: 'tests/screenshots/phase3-session-expired-1024x576.png' });
  await contextA.close(); await contextB.close();
});
