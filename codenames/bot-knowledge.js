// ── 역색인(모듈 로드 시 1회 구성) ──────────────────────────────────────
/**
 * 태그 → 그 태그를 가진 단어 목록 역색인.
 * TAG_MAP을 1회 순회해 구성한다(이후 조회는 O(1)).
 * @type {Object<string, string[]>}
 */
const TAG_TO_WORDS = (() => {
  /** @type {Object<string, string[]>} */
  const idx = {};
  for (const [word, tags] of Object.entries(TAG_MAP)) {
    for (const tag of tags) {
      (idx[tag] || (idx[tag] = [])).push(word);
    }
  }
  return idx;
})();

/**
 * 주어진 태그를 가진 단어 목록을 반환한다.
 * @param {string} tag 태그명
 * @returns {string[]} 해당 태그를 가진 단어 배열(없으면 빈 배열)
 */
export function wordsForTag(tag) {
  return TAG_TO_WORDS[tag] || [];
}

/**
 * 단어의 태그 목록을 반환한다.
 * @param {string} word 단어
 * @returns {string[]} 태그 배열(없으면 빈 배열)
 */
export function tagsForWord(word) {
  return TAG_MAP[word] || [];
}

/**
 * 여러 단어의 공통 태그를 빈도(=공유 단어 수)가 높은 순으로 반환한다.
 * 한 단어라도 포함하는 태그를 모은 뒤, 입력 단어 중 몇 개가 그 태그를 갖는지로 정렬한다.
 * 완전 교집합(모든 단어가 공유)이 가장 앞에 오고, 부분 공유 태그가 뒤따른다.
 * @param {string[]} words 단어 배열
 * @returns {Array<{tag: string, count: number}>} { 태그, 공유 단어 수 } 배열(count 내림차순)
 */
export function commonTags(words) {
  /** @type {Object<string, number>} */
  const freq = {};
  for (const w of words) {
    for (const tag of TAG_MAP[w] || []) {
      freq[tag] = (freq[tag] || 0) + 1;
    }
  }
  return Object.entries(freq)
    .map(([tag, count]) => ({ tag, count }))
    .sort((a, b) => b.count - a.count || a.tag.localeCompare(b.tag));
}

/**
 * 단어 풀 전체의 태그 통계를 반환한다(선택적 분석용).
 * @returns {Array<{tag: string, count: number}>} { 태그, 단어 수 } 배열(count 내림차순)
 */
export function allTags() {
  return Object.entries(TAG_TO_WORDS)
    .map(([tag, list]) => ({ tag, count: list.length }))
    .sort((a, b) => b.count - a.count || a.tag.localeCompare(b.tag));
}
