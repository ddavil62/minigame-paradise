/**
 * 단어 배열을 검증한다 (개발 편의용).
 * 중복이 있으면 첫 번째 중복 단어를 콘솔에 경고로 출력한다.
 * @returns {{count: number, unique: number}}
 */
export function checkWordPack() {
  const set = new Set();
  for (const w of WORDS) {
    if (set.has(w)) {
      console.warn(`[words] 중복 단어: ${w}`);
    }
    set.add(w);
  }
  return { count: WORDS.length, unique: set.size };
}
