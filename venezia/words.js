/**
 * 주어진 난이도에서 랜덤 단어 1개를 반환한다.
 * @param {'easy'|'medium'|'hard'} difficulty
 * @returns {string}
 */
export function getRandomWord(difficulty) {
  const pool = WORDS[difficulty] || WORDS.easy;
  return pool[Math.floor(Math.random() * pool.length)];
}

/**
 * 경과 시간에 따라 난이도(가중치)를 결정하고 랜덤 단어를 반환한다.
 * @param {number} elapsedSec 게임 시작 후 경과 초
 * @returns {{ text: string, difficulty: 'easy'|'medium'|'hard' }}
 */
export function pickWordByTime(elapsedSec) {
  const rand = Math.random();
  if (elapsedSec < 30) {
    // 0~29초: 초급만
    return { text: getRandomWord('easy'), difficulty: 'easy' };
  } else if (elapsedSec < 60) {
    // 30~59초: 초급 40%, 중급 60%
    const diff = rand < 0.4 ? 'easy' : 'medium';
    return { text: getRandomWord(diff), difficulty: diff };
  } else {
    // 60초+: 초급 20%, 중급 40%, 고급 40%
    let diff;
    if (rand < 0.2) diff = 'easy';
    else if (rand < 0.6) diff = 'medium';
    else diff = 'hard';
    return { text: getRandomWord(diff), difficulty: diff };
  }
}
